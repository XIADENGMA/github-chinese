import { describe, expect, it } from 'vitest'
import { simplifiedChars } from '../../../scripts/data/simplified-only'

describe('simplifiedChars', () => {
  it.each([
    '設定',
    '儲存庫',
    '議題',
    '提取要求',
    '程式碼',
    '檔案',
    '帳號',
    '通知',
    '討論',
    '發行版本',
    '工作流程',
    '里程碑',
    '雇主',
    '公里',
    '佔位',
    '範圍',
    '採用',
    '雲端',
    '這裡',
    '之後',
    '基於',
    '什麼',
    '別名',
    '推薦',
    '馬德里',
    '斯里蘭卡',
    '千里達及托巴哥',
    '史瓦希里文',
    '佛羅里達州'
  ])('繁体「%s」不报', text => {
    expect(simplifiedChars(text)).toEqual([])
  })

  it.each([
    ['无法載入', ['无']],
    ['合併之后', ['后']],
    ['基于 Sample text', ['于']],
    ['這是什么', ['么']],
    ['别名', ['别']],
    ['推荐', ['荐']],
    ['範围', ['围']],
    ['范圍', ['范']],
    ['采用', ['采']],
    ['占位', ['占']],
    ['意味着', ['着']],
    ['广告', ['广']],
    ['价格', ['价']],
    ['损坏', ['损', '坏']],
    ['这里', ['这', '里']],
    ['云端', ['云']],
    ['设置设置', ['设']]
  ])('「%s」报 %j', (text, chars) => {
    expect(simplifiedChars(text)).toEqual(chars)
  })
})
