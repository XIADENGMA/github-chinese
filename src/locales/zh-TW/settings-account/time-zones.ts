function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

/** 时区名的正则片段：按长度降序排列，长名优先尝试 */
const ZONE_SOURCE = Object.keys(TIME_ZONES)
  .sort((a, b) => b.length - a.length)
  .map(escapeRegExp)
  .join('|')

/**
 * 公开个人资料（/settings/profile）的时区下拉框：“(GMT+08:00) Beijing” → “(GMT+08:00) 北京”。
 * 只匹配已知时区名，偏移量原样保留；括号内只有英文和数字，用半角，与后面的中文隔一个空格。
 */
export default {
  regexp: [
    [
      new RegExp(`^\\((GMT|UTC)([+-]\\d{2}:\\d{2})?\\) (${ZONE_SOURCE})$`),
      (_, prefix: string, offset: string, zone: string) => `(${prefix}${offset}) ${TIME_ZONES[zone] ?? zone}`
    ]
  ]
} satisfies PageDictionary
