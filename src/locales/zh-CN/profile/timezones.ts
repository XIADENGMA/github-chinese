/** 转义正则元字符：时区名含括号、点号 */
function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

const ZONE_SOURCE = Object.keys(TIME_ZONES).map(escapeRegExp).join('|')

/** 时区下拉选项：(GMT+08:00) Beijing → (GMT+08:00) 北京；偏移量照抄，名称查表 */
